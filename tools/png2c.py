"""Converts a PNG into a palette bitmap header for arcade::Bitmap (see src/core/bitmap.h).

usage: python tools/png2c.py picture.png name [--rle] -o src/games/<game>/name_art.h

The image is reduced to at most 16 colours (4 bits per pixel, two pixels per byte, high nibble first). Transparent
pixels are not supported: draw the card background yourself. With --rle the packed bytes are run-length coded as
pairs (count 1..255, byte); this pays off for flat pixel art. The output is a header with const arrays in flash.
Draw it with ui::drawBitmap(assets::name, x, y) from ui/gfx.h.

Flash cost per card: w*h/2 bytes raw (120x78 = 4.7 KB), usually 1-3 KB with --rle, plus 32 bytes of palette.
"""
import sys

from PIL import Image


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def convert(path, rle):
    img = Image.open(path).convert("RGB")
    w, h = img.size
    q = img.quantize(colors=16, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    flat = list(q.getdata())
    pal = q.getpalette()[: 16 * 3]
    colors = max(flat) + 1
    palette = [rgb565(pal[i * 3], pal[i * 3 + 1], pal[i * 3 + 2]) for i in range(colors)]

    stream = flat + ([0] if len(flat) % 2 else [])
    packed = bytes((stream[i] << 4) | stream[i + 1] for i in range(0, len(stream), 2))
    if rle:
        out = bytearray()
        i = 0
        while i < len(packed):
            n = 1
            while i + n < len(packed) and packed[i + n] == packed[i] and n < 255:
                n += 1
            out += bytes((n, packed[i]))
            i += n
        packed = bytes(out)
    return w, h, palette, packed


def emit(name, w, h, palette, data, rle):
    lines = ["#pragma once", "", '#include "core/bitmap.h"', "", "// Generated by tools/png2c.py, do not edit.",
             "namespace assets {", "",
             f"static const uint16_t {name}_palette[{len(palette)}] = {{" + ", ".join(f"0x{c:04X}" for c in palette) + "};",
             f"static const uint8_t {name}_data[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i : i + 16]) + ",")
    lines += ["};",
              f"static const arcade::Bitmap {name} = {{{w}, {h}, {name}_palette, {len(palette)}, {name}_data, {len(data)}, "
              f"{'true' if rle else 'false'}}};",
              "", "}  // namespace assets", ""]
    return "\n".join(lines)


def main():
    argv = sys.argv[1:]
    out_path = None
    if "-o" in argv:  # prefer -o over shell redirection: PowerShell would write UTF-16
        i = argv.index("-o")
        out_path = argv[i + 1]
        del argv[i : i + 2]
    args = [a for a in argv if not a.startswith("--")]
    if len(args) != 2:
        raise SystemExit(__doc__)
    rle = "--rle" in argv
    w, h, palette, data = convert(args[0], rle)
    text = emit(args[1], w, h, palette, data, rle)
    if out_path:
        with open(out_path, "w", encoding="ascii", newline="\n") as f:
            f.write(text)
    else:
        sys.stdout.write(text)
    print(f"{args[1]}: {w}x{h}, {len(palette)} colours, {len(data)} bytes{' (rle)' if rle else ''}", file=sys.stderr)


if __name__ == "__main__":
    main()
